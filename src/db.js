// ------------------------------------------------------------------------------
// หน้าที่ : เปิดสายเชื่อมต่อ MySQL ไว้ล่วงหน้าและให้ไฟล์อื่นยืมใช้ผ่าน pool.query()
// ทำไม   : ไม่ต้องเสียเวลาเปิดการเชื่อมต่อใหม่ทุก request และจำกัดจำนวนสายไม่ให้ DB ล่ม
// Sprint : 1 | Phase 1
// ==============================================================================

// ทำไม: ใช้ mysql2/promise เพื่อเขียนแบบ async/await ได้ ไม่ต้องซ้อน callback
const mysql = require("mysql2/promise");

// ------------------------------------------------------------------------------
// 1. สร้าง Pool จากค่าใน .env
// ------------------------------------------------------------------------------
// ทำไม: ดึงรหัสผ่านจาก process.env แทนการเขียนตรง ๆ ในโค้ด
// ถามอาจารย์: ทำไมใช้ Pool แทนการ connect ครั้งเดียว
//             -> Pool ยืม/คืนสายได้ รองรับหลาย request พร้อมกัน และสร้างสายใหม่ให้เองถ้าสายหลุด
const pool = mysql.createPool({
  host: process.env.DB_HOST,
  port: process.env.DB_PORT,
  user: process.env.DB_USER,
  password: process.env.DB_PASSWORD,
  database: process.env.DB_NAME,

  // หน้าที่: ถ้าสายเต็มทั้ง 10 สาย request ถัดไปเข้าคิวรอ ไม่ถูกปฏิเสธทันที
  waitForConnections: true,
  connectionLimit: 10,
  queueLimit: 0, // 0 = คิวรอไม่จำกัดความยาว
});

module.exports = pool;
